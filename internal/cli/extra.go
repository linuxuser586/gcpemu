// providerUniverseDomain is the universe_domain the provider blocks set.
// Any non-Google value makes the provider (>= 7.2) skip its hard-coded
// userinfo lookup, which no *_custom_endpoint reaches. An API left without
// an endpoint is addressed as <api>.gcpemu.invalid, which never resolves
// (RFC 6761), so it fails instead of reaching Google.
const providerUniverseDomain = emu.InvalidUniverse

// betaPaths overrides a provider endpoint's base path in the google-beta
// block, where the provider calls a beta API version.
var betaPaths = map[string]string{
	"container_custom_endpoint": "/container/v1beta1/",
}

func (o *rootOpts) tofuProviderCmd() *cobra.Command {
	var project, region string
	var beta bool
	cmd := &cobra.Command{
		Use:   "tofu-provider",
		Short: "Print an OpenTofu provider \"google\" block pointing at the instance",
		Long: `Print an OpenTofu provider "google" block pointing at the instance.

--beta also prints a provider "google-beta" block with the same Endpoint
overrides, container's at /container/v1beta1/. It is opt-in because the block makes
OpenTofu require the hashicorp/google-beta provider.

The blocks set universe_domain = "gcpemu.invalid" so the provider skips its
caller-email lookup at openidconnect.googleapis.com, which no Endpoint
override covers. Providers older than 7.2 ignore it for that lookup and
still call Google on every run, or stall without DNS. Upgrade them, or set
HTTPS_PROXY to an address that refuses connections.`,
		RunE: func(cmd *cobra.Command, args []string) error {
			cfg, err := o.load(cmd.Flags())
			if err != nil {
				return err
			}
			c, err := clientFor(cfg)
			if err != nil {
				return err
			}
			b, err := c.get("/_emu/v1/info")
			if err != nil {
				return err
			}
			var info struct{ Services []string }
			_ = json.Unmarshal(b, &info)
			running := map[string]bool{}
			for _, s := range info.Services {
				running[s] = true
			}
			out := cmd.OutOrStdout()
			fmt.Fprintf(out, "# Generated by `gcpemu tofu-provider` for instance %q.\n", cfg.Instance)
			block := func(name string, paths map[string]string) {
				fmt.Fprintf(out, "provider %q {\n", name)
				fmt.Fprintf(out, "  project      = %q\n", project)
				fmt.Fprintf(out, "  region       = %q\n", region)
				fmt.Fprintln(out, `  access_token = "owner" # accepted as the default principal`)
				fmt.Fprintln(out, "  # Skips the provider's userinfo lookup at openidconnect.googleapis.com (#155).")
				fmt.Fprintf(out, "  universe_domain = %q\n", providerUniverseDomain)
				fmt.Fprintln(out)
				for _, e := range providerEndpoints {
					if running[e.service] {
						path := e.path
						if p, ok := paths[e.setting]; ok {
							path = p
						}
						fmt.Fprintf(out, "  %-36s = %q\n", e.setting, c.base+path)
					}
				}
				fmt.Fprintln(out, "}")
			}
			block("google", nil)
			if beta {
				fmt.Fprintln(out)
				block("google-beta", betaPaths)
			}
			return nil
		},
	}
	cmd.Flags().StringVar(&project, "project", "gcpemu-project", "project for the provider block")
	cmd.Flags().StringVar(&region, "region", "us-central1", "region for the provider block")
	cmd.Flags().BoolVar(&beta, "beta", false, "also print a provider \"google-beta\" block")
	return cmd
}

func (o *rootOpts) faultCmd() *cobra.Command {
	root := &cobra.Command{Use: "fault", Short: "Manage fault-injection rules"}
	var r fault.Rule
	var latency time.Duration
	add := &cobra.Command{
		Use:   "add",
		Short: "Add a fault-injection rule",
		RunE: func(cmd *cobra.Command, args []string) error {
			r.Latency = fault.Duration(latency)
			body, _ := json.Marshal(r)
			return o.adminCall(cmd, http.MethodPost, "/_emu/v1/faults", body)
		},
	}
	f := add.Flags()
	f.StringVar(&r.ID, "id", "", "rule ID (default generated)")
	f.StringVar(&r.Service, "service", "", "Service ID")
	f.StringVar(&r.Method, "method", "", "regexp on method (\"GET /storage/v1/b\" or \"/google.pubsub.v1.Publisher/Publish\")")
	f.StringVar(&r.Resource, "resource", "", "regexp on request path")
	f.StringVar(&r.Code, "code", "", "error code name, e.g. UNAVAILABLE")
	f.IntVar(&r.HTTPStatus, "http-status", 0, "override HTTP status")
	f.DurationVar(&latency, "latency", 0, "added latency")
	f.BoolVar(&r.Drop, "drop", false, "drop the connection")
	f.Float64Var(&r.Probability, "probability", 0, "probability in (0,1]; 0 = always")
	f.IntVar(&r.Count, "count", 0, "fire at most N times; 0 = unlimited")
	f.BoolVar(&r.Disabled, "disabled", false, "add the rule disabled")

	list := &cobra.Command{
		Use:   "list",
		Short: "List fault-injection rules",
		RunE: func(cmd *cobra.Command, args []string) error {
			return o.adminCall(cmd, http.MethodGet, "/_emu/v1/faults", nil)
		},
	}
	clearCmd := &cobra.Command{
		Use:   "clear [ID]",
		Short: "Remove one rule, or all rules",
		Args:  cobra.MaximumNArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			path := "/_emu/v1/faults"
			if len(args) == 1 {
				path += "/" + args[0]
			}
			return o.adminCall(cmd, http.MethodDelete, path, nil)
		},
	}
	toggle := func(name, short string, disabled bool) *cobra.Command {
		return &cobra.Command{
			Use:   name + " ID",
			Short: short,
			Args:  cobra.ExactArgs(1),
			RunE: func(cmd *cobra.Command, args []string) error {
				body, _ := json.Marshal(map[string]bool{"disabled": disabled})
				return o.adminCall(cmd, http.MethodPatch, "/_emu/v1/faults/"+args[0], body)
			},
		}
	}
	root.AddCommand(add, list, clearCmd,
		toggle("enable", "Let a disabled rule fire again", false),
		toggle("disable", "Stop a rule firing, keeping it and its hit count", true))
	return root
}

// snapshotTimeout bounds saving and restoring a State snapshot, which
// dumps or replays every Cloud SQL instance's databases.
const snapshotTimeout = 30 * time.Minute

func (o *rootOpts) snapshotCmd() *cobra.Command {
	root := &cobra.Command{Use: "snapshot", Short: "Save and restore State snapshots of a running instance"}
	save := &cobra.Command{
		Use:   "save NAME",
		Short: "Save all state as the State snapshot NAME, replacing one of that name",
		Args:  cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			body, _ := json.Marshal(map[string]string{"name": args[0]})
			return o.adminCallTimeout(cmd, http.MethodPost, "/_emu/v1/snapshots", body, snapshotTimeout)
		},
	}
	restore := &cobra.Command{
		Use:   "restore NAME",
		Short: "Replace all state with the State snapshot NAME, keeping configuration",
		Args:  cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			return o.adminCallTimeout(cmd, http.MethodPost, "/_emu/v1/snapshots/"+url.PathEscape(args[0])+"/restore", nil, snapshotTimeout)
		},
	}
	list := &cobra.Command{
		Use:   "list",
		Short: "List State snapshots",
		RunE: func(cmd *cobra.Command, args []string) error {
			return o.adminCall(cmd, http.MethodGet, "/_emu/v1/snapshots", nil)
		},
	}
	del := &cobra.Command{
		Use:   "delete NAME",
		Short: "Delete the State snapshot NAME",
		Args:  cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			return o.adminCall(cmd, http.MethodDelete, "/_emu/v1/snapshots/"+url.PathEscape(args[0]), nil)
		},
	}
	root.AddCommand(save, restore, list, del)
	return root
}

