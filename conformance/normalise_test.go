//go:build conformance

package conformance

import (
	"cmp"
	"encoding/json"
	"errors"
	"fmt"
	"maps"
	"regexp"
	"slices"
	"strings"
	"time"
)

// runIDs are the values that differ between targets and runs and become
// <project>, <project-number> and <suffix>.
type runIDs struct {
	project, number, suffix string
}

// Option adjusts how a test's Exchanges are normalised and compared.
type Option struct {
	apply func(*rules) error
}

// rules are a test's Options.
type rules struct {
	ignore    map[string]string // field path → reason
	unordered map[string]string // field path → sort key
	generated []string          // extra keys whose values are generated
	runOnly   map[string]bool   // field paths of lists to keep only this run's elements of
	messages  bool              // compare error messages
}

// Ignore drops the field at path from every body, on both targets. path
// is a body's field names joined by "." with "[]" after an array, e.g.
// "acl[].etag". reason says why the field may differ and is required.
func Ignore(path, reason string) Option {
	return Option{func(r *rules) error {
		if strings.TrimSpace(reason) == "" {
			return fmt.Errorf("conformance: Ignore(%q) needs a reason", path)
		}
		r.ignore[path] = reason
		return nil
	}}
}

// Unordered compares the repeated field at path (Ignore's syntax) in any
// order, by sorting its elements on key ("" for "name"). Elements that
// are not objects sort by their JSON.
func Unordered(path, key string) Option {
	return Option{func(r *rules) error {
		if key == "" {
			key = "name"
		}
		r.unordered[path] = key
		return nil
	}}
}

// RunOnly keeps, of the repeated field at path (Ignore's syntax), only
// the elements that mention this run's suffix: a list in a real project
// also returns what other runs and people made.
func RunOnly(path string) Option {
	return Option{func(r *rules) error {
		r.runOnly[path] = true
		return nil
	}}
}

// Generated makes key a field whose values the target generates, as it
// does for "id": each distinct value becomes <key:n>. reason says why the
// value is generated and is required.
func Generated(key, reason string) Option {
	return Option{func(r *rules) error {
		if strings.TrimSpace(reason) == "" {
			return fmt.Errorf("conformance: Generated(%q) needs a reason", key)
		}
		r.generated = append(r.generated, key)
		return nil
	}}
}

// CompareMessages compares the human-readable message of errors too.
func CompareMessages() Option {
	return Option{func(r *rules) error { r.messages = true; return nil }}
}

// generatedKeys are the fields whose values are generated by default, and
// the placeholder kind of each: a repeated field shares its element's.
var generatedKeys = map[string]string{
	"id": "id", "generation": "generation", "uniqueId": "uniqueId", "oauth2ClientId": "oauth2ClientId",
	"messageId": "messageId", "messageIds": "messageId", "ackId": "ackId", "ackIds": "ackId",
}

// minEmbedded is the shortest generated value that is also replaced
// inside other strings (a mediaLink's generation, an ID in a path); a
// shorter one would match by chance.
const minEmbedded = 6

var (
	urlHost     = regexp.MustCompile(`https?://[^/\s"?#]+`)
	timestampRE = regexp.MustCompile(`^\d{4}-\d{2}-\d{2}[Tt ]`)
	// An etag keeps its shape: weak or strong, quoted or not, and an
	// unquoted one a base64url token (GCS's "CAE=", IAM's "BwX…").
	etagRE   = regexp.MustCompile(`^(W/)?"([!#-~]+)"$`)
	etagBare = regexp.MustCompile(`^[A-Za-z0-9+/=_-]+$`)
	// operationRE matches a long-running Operation's name, whose last
	// segment the target generates.
	operationRE = regexp.MustCompile(`(operations/)([^/\s"?#]+)`)
)

// normaliser turns one test's raw Exchanges into a Recording. It keeps the
// placeholders it has given, so one value has one placeholder in all the
// test's Exchanges.
type normaliser struct {
	ids       runIDs
	rules     rules
	generated map[string]string // key → placeholder kind
	given     map[string]string // kind + "\x00" + raw value → placeholder
	embedded  map[string]string // raw generated value → placeholder, for replacing inside strings
	counts    map[string]int
}

// newNormaliser returns a normaliser for one test run with ids.
func newNormaliser(ids runIDs, opts ...Option) (*normaliser, error) {
	n := &normaliser{
		ids:      ids,
		rules:    rules{ignore: map[string]string{}, unordered: map[string]string{}, runOnly: map[string]bool{}},
		given:    map[string]string{},
		embedded: map[string]string{},
		counts:   map[string]int{},
	}
	var errs []error
	for _, o := range opts {
		errs = append(errs, o.apply(&n.rules))
	}
	n.generated = maps.Clone(generatedKeys)
	for _, k := range n.rules.generated {
		n.generated[k] = k
	}
	return n, errors.Join(errs...)
}

// recording normalises raw, in order.
func (n *normaliser) recording(raw []Exchange) Recording {
	r := Recording{Exchanges: []Exchange{}}
	for _, e := range raw {
		e.Request.Body = n.mark(n.strip(e.Request.Body, ""), "")
		e.Response.Body = n.mark(n.strip(e.Response.Body, ""), "")
		e.Request.Path = n.embed(n.operations(n.fixed(e.Request.Path)))
		e.Request.Body = n.embedAll(e.Request.Body)
		e.Response.Body = n.embedAll(e.Response.Body)
		r.Exchanges = append(r.Exchanges, e)
	}
	return r
}

// fixed replaces the run identifiers and URL hosts in s.
func (n *normaliser) fixed(s string) string {
	s = urlHost.ReplaceAllString(s, "<host>")
	for _, r := range []struct{ raw, p string }{
		{n.ids.project, "<project>"}, {n.ids.number, "<project-number>"}, {n.ids.suffix, "<suffix>"},
	} {
		if r.raw != "" {
			s = strings.ReplaceAll(s, r.raw, r.p)
		}
	}
	return s
}

// strip drops ignored fields, applies fixed to every string and sorts
// unordered arrays. path is v's field path.
func (n *normaliser) strip(v any, path string) any {
	switch v := v.(type) {
	case map[string]any:
		out := make(map[string]any, len(v))
		for k, x := range v {
			p := join(path, k)
			if _, ok := n.rules.ignore[p]; ok {
				continue
			}
			out[k] = n.strip(x, p)
		}
		return out
	case []any:
		out := make([]any, len(v))
		for i, x := range v {
			out[i] = n.strip(x, path+"[]")
		}
		if n.rules.runOnly[path] {
			out = slices.DeleteFunc(out, func(x any) bool { return !strings.Contains(show(x), "<suffix>") })
		}
		if key, ok := n.rules.unordered[path]; ok {
			slices.SortStableFunc(out, func(a, b any) int { return strings.Compare(sortKey(a, key), sortKey(b, key)) })
		}
		return out
	case string:
		return n.fixed(v)
	}
	return v
}

// mark replaces generated values, etags and timestamps with placeholders,
// visiting keys in order so that both targets number them alike.
func (n *normaliser) mark(v any, key string) any {
	switch v := v.(type) {
	case map[string]any:
		for _, k := range slices.Sorted(maps.Keys(v)) {
			v[k] = n.mark(v[k], k)
		}
		return v
	case []any:
		for i := range v {
			v[i] = n.mark(v[i], key)
		}
		return v
	case json.Number:
		if kind, ok := n.generated[key]; ok {
			return n.placeholder(kind, v.String())
		}
	case string:
		// A value made from the test's own names is not generated.
		kind, generated := n.generated[key]
		generated = generated && !strings.Contains(v, "<suffix>")
		switch {
		case generated:
			return n.placeholder(kind, v)
		case key == "etag":
			// A malformed etag is left as is, so it mismatches.
			if m := etagRE.FindStringSubmatch(v); m != nil {
				return m[1] + `"` + n.placeholder("etag", m[2]) + `"`
			}
			if etagBare.MatchString(v) {
				return n.placeholder("etag", v)
			}
		case timestampRE.MatchString(v):
			// A malformed timestamp is left as is, so it mismatches.
			if _, err := time.Parse(time.RFC3339Nano, v); err == nil {
				return "<timestamp>"
			}
		default:
			return n.operations(v)
		}
	}
	return v
}

// operations replaces the ID of each Operation named in s.
func (n *normaliser) operations(s string) string {
	return operationRE.ReplaceAllStringFunc(s, func(m string) string {
		sub := operationRE.FindStringSubmatch(m)
		return sub[1] + n.placeholder("operation", sub[2])
	})
}

// placeholder is the placeholder of kind for raw, given on first use.
func (n *normaliser) placeholder(kind, raw string) string {
	k := kind + "\x00" + raw
	if p, ok := n.given[k]; ok {
		return p
	}
	n.counts[kind]++
	p := fmt.Sprintf("<%s:%d>", kind, n.counts[kind])
	n.given[k] = p
	if kind != "etag" && len(raw) >= minEmbedded {
		n.embedded[raw] = p
	}
	return p
}

// embed replaces generated values inside s, longest first.
func (n *normaliser) embed(s string) string {
	raws := slices.SortedFunc(maps.Keys(n.embedded), func(a, b string) int {
		return cmp.Or(len(b)-len(a), strings.Compare(a, b))
	})
	for _, raw := range raws {
		s = strings.ReplaceAll(s, raw, n.embedded[raw])
	}
	return s
}

// embedAll applies embed to every string in v that is not already a
// placeholder.
func (n *normaliser) embedAll(v any) any {
	switch v := v.(type) {
	case map[string]any:
		for k, x := range v {
			v[k] = n.embedAll(x)
		}
	case []any:
		for i, x := range v {
			v[i] = n.embedAll(x)
		}
	case string:
		return n.embed(v)
	}
	return v
}

// join is path with field k.
func join(path, k string) string {
	if path == "" {
		return k
	}
	return path + "." + k
}

// sortKey is what an element of an unordered array sorts on: its key
// field, or its JSON when it is not an object or lacks the field.
func sortKey(v any, key string) string {
	if m, ok := v.(map[string]any); ok {
		if s, ok := m[key].(string); ok {
			return s
		}
	}
	b, _ := json.Marshal(v)
	return string(b)
}
